#!/usr/bin/env node
// P5-78 spike (accordproject/concerto-rust#420): precompile
// concertino.schema.json with ajv's standalone code generation, so the
// `./schema` subpath ships compiled checks instead of the ajv compiler
// (no `new Function`, so strict CSP is fine, and ~120 KB less).
//
//   node migration/spikes/P5-78/bin/build-schema-validator.mjs
//
// Writes src/concertino/schema-validator.mjs (ESM; imports only small ajv
// runtime helpers, if the schema needs any).
import fs from 'fs';
import path from 'path';
import url from 'url';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);
const HERE = path.dirname(url.fileURLToPath(import.meta.url));
const SPIKE = path.resolve(HERE, '..');
const REPO = path.resolve(SPIKE, '..', '..', '..');
const ajvDir = path.join(REPO, 'node_modules', 'ajv');
const Ajv = require(ajvDir).default;
const standaloneCode = require(path.join(ajvDir, 'dist', 'standalone')).default;

const schema = JSON.parse(fs.readFileSync(path.join(SPIKE, 'src', 'concertino', 'spec', 'concertino.schema.json'), 'utf8'));
const ajv = new Ajv({ code: { source: true, esm: true }, allErrors: false, inlineRefs: false });
const validate = ajv.compile(schema);
let code = standaloneCode(ajv, validate);
const out = path.join(SPIKE, 'src', 'concertino', 'schema-validator.mjs');
fs.writeFileSync(out, `// Generated by bin/build-schema-validator.mjs from spec/concertino.schema.json (ajv ${require(path.join(ajvDir, 'package.json')).version} standalone). Do not edit.\n${code}\n`);
console.log(`wrote ${path.relative(REPO, out)} (${code.length} bytes; runtime requires: ${(code.match(/require\(/g) || []).length})`);
